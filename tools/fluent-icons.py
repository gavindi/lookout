#!/usr/bin/env python3
"""Import the Fluent System Icon aliases Lookout uses for its optional pack.

The pack is a *partial* GTK icon theme named Lookout-Fluent.  Its files are
named after the icon names Lookout already requests (for example
``mail-send-symbolic.svg``), so switching to Fluent needs no call-site
changes; the theme inherits the user's GNOME theme for everything it does not
override.  ``manifest.tsv`` is the source of truth: one alias, one Fluent asset
name and the Fluent style (regular or filled) per row.

Usage:
    python3 tools/fluent-icons.py --fetch
        Download every manifest row from the pinned upstream revision,
        normalise it to a monochrome symbolic SVG and rewrite the gresource
        block.

    python3 tools/fluent-icons.py --source-dir /path/to/fluentui-system-icons
        The same, from a local checkout or extracted tarball (assets/...).

    python3 tools/fluent-icons.py --check
        Verify the generated SVGs and resources.gresource.xml match the
        manifest.  Exits non-zero on drift.

Installing the icons is a build-time action; Lookout never downloads them.
The upstream project is MIT licensed (see ``source/data/icons/fluent/LICENSE``).
"""

from __future__ import annotations

import argparse
import re
import sys
import urllib.request
from pathlib import Path

# Pinned so regeneration is reproducible.  Bump deliberately.
PINNED_REF = "463d58b8186f874ab2f51cf0a08b4ff5097c912f"
UPSTREAM = "https://raw.githubusercontent.com/microsoft/fluentui-system-icons/{ref}/assets/{asset}/SVG/{file}"

ROOT = Path(__file__).resolve().parents[1]
PACK_DIR = ROOT / "source" / "data" / "icons" / "fluent"
MANIFEST = PACK_DIR / "manifest.tsv"
ICON_DIR = PACK_DIR / "scalable" / "actions"
GRESOURCE = ROOT / "source" / "data" / "resources.gresource.xml"

BLOCK_BEGIN = "    <!-- fluent-icons:begin (generated by tools/fluent-icons.py) -->"
BLOCK_END = "    <!-- fluent-icons:end -->"


def read_manifest() -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    seen: set[str] = set()
    for number, line in enumerate(MANIFEST.read_text().splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 3:
            raise SystemExit(f"{MANIFEST}:{number}: expected 3 tab-separated fields, got {len(fields)}")
        alias, asset, style = (field.strip() for field in fields)
        if style not in ("regular", "filled"):
            raise SystemExit(f"{MANIFEST}:{number}: style must be regular or filled, got {style!r}")
        if alias in seen:
            raise SystemExit(f"{MANIFEST}:{number}: duplicate alias {alias}")
        if not alias.endswith("-symbolic"):
            raise SystemExit(f"{MANIFEST}:{number}: {alias} is not a symbolic icon name")
        seen.add(alias)
        rows.append((alias, asset, style))
    return rows


def snake_case(asset: str) -> str:
    return asset.lower().replace(" ", "_").replace("-", "_")


def upstream_file(asset: str, style: str) -> str:
    return f"ic_fluent_{snake_case(asset)}_24_{style}.svg"


def normalise(svg: str) -> str:
    """Reduce Fluent's ``#212121`` artwork to a symbolic, recolourable glyph.

    GTK recolours an icon whose name ends in ``-symbolic``; using one solid
    paint everywhere keeps the alpha shape exact and lets the theme's text
    colour (including high contrast) shine through.  ``fill="none"`` and
    ``stroke="none"`` are holes and stay untouched.
    """
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r"<title>.*?</title>", "", svg, flags=re.S | re.I)
    svg = re.sub(r'\sclass="[^"]*"', "", svg)
    svg = re.sub(r'\bfill="(?!none")[^"]*"', 'fill="#000000"', svg)
    svg = re.sub(r'\bstroke="(?!none")[^"]*"', 'stroke="#000000"', svg)
    # Fluent SVGs are 24x24 with a viewBox; drop the fixed pixel size so GTK
    # can render them at the requested ribbon size without a second scale.
    svg = re.sub(r'\s(width|height)="24"', "", svg, count=2)
    return svg.strip() + "\n"


def fetch(url: str) -> str:
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode("utf-8")


def generate(rows: list[tuple[str, str, str]], source_dir: Path | None) -> None:
    ICON_DIR.mkdir(parents=True, exist_ok=True)
    for alias, asset, style in rows:
        filename = upstream_file(asset, style)
        if source_dir is None:
            url = UPSTREAM.format(ref=PINNED_REF, asset=asset.replace(" ", "%20"), file=filename)
            raw = fetch(url)
        else:
            source = source_dir / "assets" / asset / "SVG" / filename
            if not source.exists():
                raise SystemExit(f"missing upstream icon: {source}")
            raw = source.read_text()
        (ICON_DIR / f"{alias}.svg").write_text(normalise(raw))
    rewrite_gresource(rows)
    print(f"wrote {len(rows)} icons to {ICON_DIR.relative_to(ROOT)}")


def rewrite_gresource(rows: list[tuple[str, str, str]]) -> None:
    text = GRESOURCE.read_text()
    lines = [BLOCK_BEGIN]
    for alias, _asset, _style in sorted(rows):
        target = f"icons/Lookout-Fluent/scalable/actions/{alias}.svg"
        lines.append(f'        <file alias="{target}">icons/fluent/scalable/actions/{alias}.svg</file>')
    lines.append(BLOCK_END)
    block = "\n".join(lines)
    if BLOCK_BEGIN in text:
        text = re.sub(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END), block, text, flags=re.S)
    else:
        text = text.replace("    </gresource>", block + "\n    </gresource>")
    GRESOURCE.write_text(text)


def check(rows: list[tuple[str, str, str]]) -> int:
    errors: list[str] = []
    expected = {f"{alias}.svg" for alias, _asset, _style in rows}
    actual = {path.name for path in ICON_DIR.glob("*.svg")} if ICON_DIR.exists() else set()
    for name in sorted(expected - actual):
        errors.append(f"missing generated icon: {name}")
    for name in sorted(actual - expected):
        errors.append(f"unlisted icon on disk (add it to manifest.tsv or delete it): {name}")

    text = GRESOURCE.read_text()
    for alias, _asset, _style in rows:
        target = f'alias="icons/Lookout-Fluent/scalable/actions/{alias}.svg"'
        if target not in text:
            errors.append(f"resources.gresource.xml lacks {target}")
        svg = ICON_DIR / f"{alias}.svg"
        if svg.exists() and 'fill="#212121"' in svg.read_text():
            errors.append(f"{svg.name} still carries Fluent's default fill")

    for error in errors:
        print(f"error: {error}", file=sys.stderr)
    if errors:
        return 1
    print(f"ok: {len(rows)} Fluent aliases match the manifest and resources.gresource.xml")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--fetch", action="store_true", help="download from the pinned upstream revision")
    source.add_argument("--source-dir", type=Path, help="use a local fluentui-system-icons checkout")
    source.add_argument("--check", action="store_true", help="verify the generated pack matches the manifest")
    args = parser.parse_args()

    rows = read_manifest()
    if args.check:
        return check(rows)
    generate(rows, args.source_dir)
    return check(rows)


if __name__ == "__main__":
    raise SystemExit(main())
